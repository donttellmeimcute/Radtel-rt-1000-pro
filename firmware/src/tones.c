/* Golay (23,12): polinomio generador 0xC75. Palabra = 11 bits de paridad | 12 bits datos.
 * Datos DCS = 100 (bits fijos) + 9 bits del codigo. */
uint32_t dcs_golay_word(uint16_t code)
{
    uint32_t data = 0x800u | (code & 0x1FFu);
    uint32_t r = data << 11;
    for (int i = 22; i >= 11; i--)
        if (r & (1u << i)) r ^= 0xC75u << (i - 11);
    return (data | ((r & 0x7FFu) << 12));
}

int dtmf_freqs(char c, uint16_t *low, uint16_t *high)
{
    static const char keys[] = "123A456B789C*0#D";
    static const uint16_t lo[4] = {697, 770, 852, 941}, hi[4] = {1209, 1336, 1477, 1633};
    for (int i = 0; i < 16; i++)
        if (keys[i] == c) { *low = lo[i / 4]; *high = hi[i % 4]; return 1; }
    return 0;
}
